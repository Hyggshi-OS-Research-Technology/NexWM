import unicodedata

def ascii_fold(ch):
    if ord(ch) < 0x80:
        return ch.lower()
    d = unicodedata.normalize('NFD', ch)
    base = ''.join(c for c in d if not unicodedata.combining(c))
    base = base.lower()
    if base == 'đ':
        return 'd'
    if base == 'ð':
        return 'd'
    if base == 'þ':
        return 'th'
    if base == 'ß':
        return 'ss'
    if base == 'æ':
        return 'ae'
    if base == 'œ':
        return 'oe'
    if base == 'ø':
        return 'o'
    if base == 'ł':
        return 'l'
    out = ''.join(c for c in base if 'a' <= c <= 'z' or '0' <= c <= '9')
    return out

entries = []
ranges = [(0x00C0, 0x024F), (0x1E00, 0x1EFF), (0x0400, 0x04FF)]
for lo, hi in ranges:
    for cp in range(lo, hi + 1):
        ch = chr(cp)
        try:
            cat = unicodedata.category(ch)
        except ValueError:
            continue
        if not cat.startswith('L'):
            continue
        fold = ascii_fold(ch)
        if not fold or fold == ch:
            continue
        entries.append((ch, fold))

# longest first, so the table reads the way it is searched (UTF-8 is prefix-free, but a table that is
# ordered by length is what hde_store_fold() promises)
entries.sort(key=lambda e: (-len(e[0].encode('utf-8')), e[0]))
lines = []
lines.append('/* Generated by scripts/gen-fold-table.py — do not edit by hand.')
lines.append(' * Latin-1, Latin Extended-A/B, Vietnamese (Latin Extended Additional) and Cyrillic letters with their')
lines.append(' * ASCII fold, longest sequence first: hde_store_fold() walks this table byte by byte. */')
lines.append('#ifndef HDE_STORE_FOLD_TABLE_H')
lines.append('#define HDE_STORE_FOLD_TABLE_H')
lines.append('')
lines.append('typedef struct { const char *from; const char *to; } HdeStoreFoldPair;')
lines.append('')
lines.append('static const HdeStoreFoldPair hde_store_fold_table[] = {')
for ch, fold in entries:
    src = ''.join('\\x%02x' % b for b in ch.encode('utf-8'))
    lines.append('    { "%s", "%s" },' % (src, fold))
lines.append('};')
lines.append('')
lines.append('#endif')
open('/home/user/NexWM/apps/store/hde-store-fold.h', 'w').write('\n'.join(lines) + '\n')
print(len(entries), 'entries')
