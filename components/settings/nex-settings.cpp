    void onApply() {
        m_cfg.gaps = m_spinGaps->value();
        m_cfg.workspaceCount = m_spinWorkspaces->value();
        m_cfg.defaultLayout = m_comboLayout->currentText();
        m_cfg.borderWidth = m_spinBorderWidth->value();
        m_cfg.wallpaperPath = m_editWallpaper->text().trimmed();
        m_cfg.wallpaperMode = m_comboWallpaperMode->currentText();
        m_cfg.desktopIconSize = m_spinDesktopIconSize->value();

        /*
         * Validate wallpaper before changing anything.
         */
        if (!m_cfg.wallpaperPath.isEmpty()) {
            QFileInfo info(m_cfg.wallpaperPath);

            if (!info.exists() || !info.isFile()) {
                QMessageBox::warning(
                    this,
                    "NexSettings",
                    QString("Wallpaper image file not found:\n%1")
                        .arg(m_cfg.wallpaperPath)
                );
                return;
            }

            if (!info.isReadable()) {
                QMessageBox::warning(
                    this,
                    "NexSettings",
                    QString("Wallpaper image is not readable:\n%1")
                        .arg(m_cfg.wallpaperPath)
                );
                return;
            }
        }

        /*
         * Save the complete configuration first.
         */
        if (!saveConfig(m_cfg)) {
            QMessageBox::critical(
                this,
                "NexSettings",
                "Failed to save configuration file."
            );
            return;
        }

        /*
         * Apply wallpaper using Qt's QProcess.
         *
         * nex-settings is a Qt6 application. No GTK API is used here and
         * no child widget is manually hidden/destroyed.
         */
        if (!m_cfg.wallpaperPath.isEmpty()) {
            QProcess wallpaper;

            wallpaper.setProgram("nex-wallpaper");
            wallpaper.setArguments({
                "--set",
                m_cfg.wallpaperPath,
                "--mode",
                m_cfg.wallpaperMode
            });

            wallpaper.start();

            if (!wallpaper.waitForStarted(3000)) {
                QMessageBox::warning(
                    this,
                    "NexSettings",
                    QString("Failed to start nex-wallpaper:\n%1")
                        .arg(wallpaper.errorString())
                );
                return;
            }

            if (!wallpaper.waitForFinished(15000)) {
                wallpaper.kill();
                wallpaper.waitForFinished(2000);

                QMessageBox::warning(
                    this,
                    "NexSettings",
                    "nex-wallpaper did not finish within 15 seconds."
                );
                return;
            }

            const QByteArray stderrData =
                wallpaper.readAllStandardError();

            const QByteArray stdoutData =
                wallpaper.readAllStandardOutput();

            if (wallpaper.exitStatus() != QProcess::NormalExit ||
                wallpaper.exitCode() != 0) {

                QString details =
                    QString::fromLocal8Bit(stderrData).trimmed();

                if (details.isEmpty()) {
                    details =
                        QString::fromLocal8Bit(stdoutData).trimmed();
                }

                if (details.isEmpty()) {
                    details = "nex-wallpaper exited with an error.";
                }

                QMessageBox::warning(
                    this,
                    "NexSettings",
                    QString(
                        "Failed to apply wallpaper.\n\n"
                        "Exit code: %1\n"
                        "%2"
                    )
                    .arg(wallpaper.exitCode())
                    .arg(details)
                );
                return;
            }
        }

        /*
         * Apply NexWM IPC settings.
         */
        applyIPC(m_cfg);

        QMessageBox::information(
            this,
            "NexSettings",
            "Settings applied and saved successfully!"
        );
    }

    NexConfig m_cfg;
    QTabWidget *m_tabWidget;

    /* Appearance */
    QSpinBox *m_spinGaps;
    QSpinBox *m_spinWorkspaces;
    QComboBox *m_comboLayout;
