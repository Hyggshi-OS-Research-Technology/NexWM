struct NexConfig {
    int gaps = 8;
    int workspaceCount = 9;
    QString defaultLayout = "tiled";
    int borderWidth = 2;
    QColor borderFocus = QColor("#5b8dd9");
    QColor borderNormal = QColor("#444444");
    QString wallpaperPath;
    QString wallpaperMode = "scale";
    int desktopIconSize = 48;
};

static QString getConfigPath() {
    const char *home = getenv("HOME");
    if (!home) home = "/root";
    return QString("%1/.config/nexwm/nexwm.conf").arg(home);
}

static NexConfig loadConfig() {
    NexConfig cfg;
    QFile file(getConfigPath());
    if (!file.open(QIODevice::ReadOnly | QIODevice::Text)) return cfg;

    QTextStream in(&file);
    while (!in.atEnd()) {
        QString line = in.readLine().trimmed();
        if (line.isEmpty() || line.startsWith('#')) continue;

        int eqPos = line.indexOf('=');
        if (eqPos == -1) continue;

        QString key = line.left(eqPos).trimmed();
        QString val = line.mid(eqPos + 1).trimmed();

        if (key == "gaps") cfg.gaps = val.toInt();
        else if (key == "workspace_count") cfg.workspaceCount = val.toInt();
        else if (key == "default_layout") cfg.defaultLayout = val;
        else if (key == "border_width") cfg.borderWidth = val.toInt();
        else if (key == "border_focus") cfg.borderFocus = QColor(val);
        else if (key == "border_normal") cfg.borderNormal = QColor(val);
        else if (key == "wallpaper") cfg.wallpaperPath = val;
        else if (key == "wallpaper_mode") cfg.wallpaperMode = val;
        else if (key == "desktop_icon_size") cfg.desktopIconSize = val.toInt();
    }
    file.close();
    return cfg;
}

static bool saveConfig(const NexConfig &cfg) {
    QString path = getConfigPath();
    QFileInfo fi(path);
    QDir().mkpath(fi.absolutePath());

    QFile file(path);
    if (!file.open(QIODevice::WriteOnly | QIODevice::Text)) return false;

    QTextStream out(&file);
    out << "# NexWM Configuration File\n";
    out << "# Generated by NexSettings Control Panel (Qt6)\n\n";
    out << "gaps = " << cfg.gaps << "\n";
    out << "workspace_count = " << cfg.workspaceCount << "\n";
    out << "default_layout = " << cfg.defaultLayout << "\n";
    out << "border_width = " << cfg.borderWidth << "\n";
    out << "border_focus = " << cfg.borderFocus.name() << "\n";
    out << "border_normal = " << cfg.borderNormal.name() << "\n";
    out << "wallpaper = " << cfg.wallpaperPath << "\n";
    out << "wallpaper_mode = " << cfg.wallpaperMode << "\n";
    out << "desktop_icon_size = " << cfg.desktopIconSize << "\n";
    file.close();
    return true;
}

static void applyIPC(const NexConfig &cfg) {
    QProcess::execute("nexwmctl", {"set-gap", QString::number(cfg.gaps)});
    QProcess::execute("nexwmctl", {"set-layout", cfg.defaultLayout});
    QProcess::execute("nexwmctl", {"workspace-count", QString::number(cfg.workspaceCount)});
    QProcess::execute("nexwmctl", {"reload"});
}

